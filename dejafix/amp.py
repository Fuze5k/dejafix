"""Put the replay's ground truth and results into the datapack's own Postgres (Meko Cloud AMP).

One run builds it from scratch: it drops the datapack's `dejafix` cluster if there is one, creates it with a
writer endpoint reachable from this machine's address only, creates the tables, loads the ticket stream,
GitHub's duplicate links, every recorded replay, the judge's grades and the learnings, and runs the queries
the README quotes. The writer's password is generated by Meko Cloud and returned once: it lives in this
process only and is never printed or stored, so a later run rebuilds the cluster instead of reconnecting.

Usage: uv run python -m dejafix.amp --datapack dejafix-uv-final --replay cold=results/cold.jsonl \
           --replay warm=results/warm.jsonl --replay warm_local=results/warm-local.jsonl \
           --replay stuffed=results/baseline.jsonl --judge results/judge.jsonl
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import time
from pathlib import Path
from typing import Any

import httpx
import psycopg

from dejafix.load_docs import conversation, loaded_datapack
from dejafix.meko import Meko
from dejafix.tickets import load_links, load_pool, load_stream

CLUSTER = "dejafix"
READY_TIMEOUT = 900  # seconds; a new endpoint takes minutes to come up
PUBLIC_RESOLVER = "1.1.1.1"

SCHEMA = """
create table tickets (
    number int primary key,
    title text not null,
    url text not null,
    opened date not null,
    stream_role text not null check (stream_role in ('first', 'repeat', 'new')),
    position int not null unique
);
create table duplicate_links (
    duplicate int primary key,
    canonical int not null
);
create table outcomes (
    system text not null,
    ticket int not null references tickets,
    verdict text,
    known_issue int,
    correct boolean not null,
    exact boolean,
    reply text,
    primary key (system, ticket)
);
create table agent_runs (
    system text not null,
    ticket int not null references tickets,
    role text not null,
    tokens int not null,
    cost_usd numeric(10, 6) not null,
    seconds real not null,
    meko_tools text[] not null,
    primary key (system, ticket, role)
);
create table learnings (
    memory_id uuid primary key,
    system text not null,
    ticket int not null references tickets,
    filed_under int not null,
    learning text not null
);
create table grades (
    ticket int not null references tickets,
    system text not null,
    resolution text not null check (resolution in ('match', 'partial', 'miss')),
    wrong_claim boolean not null,
    why text not null,
    primary key (ticket, system)
);
"""

# The README quotes these; their answers go to results/amp-queries.json. Comparisons use the tickets every
# system has a record for.
QUERIES = {
    "tokens_per_ticket": """
        select o.system, count(distinct o.ticket) as tickets,
               round(avg(t.tokens)) as tokens_per_ticket, round(sum(t.cost), 2) as cost_usd
        from outcomes o
        join (select system, ticket, sum(tokens) as tokens, sum(cost_usd) as cost
              from agent_runs group by system, ticket) t using (system, ticket)
        where o.ticket in (select ticket from outcomes group by ticket
                       having count(*) = (select count(distinct system) from outcomes))
        group by o.system order by o.system""",
    "repeats_found": """
        select o.system, count(*) filter (where o.correct) as right, count(*) as repeats
        from outcomes o join tickets k on k.number = o.ticket
        where k.stream_role = 'repeat' and o.ticket in (select ticket from outcomes group by ticket
                       having count(*) = (select count(distinct system) from outcomes))
        group by o.system order by o.system""",
    "fix_reused": """
        select l.filed_under as learned_on, array_agg(distinct o.ticket order by o.ticket) as reused_by
        from learnings l
        join outcomes o on o.system = l.system and o.known_issue = l.filed_under and o.ticket <> l.ticket
        where l.system = 'warm' and o.correct
        group by l.filed_under order by count(distinct o.ticket) desc, l.filed_under""",
    "replies_matching": """
        select system, count(*) filter (where resolution = 'match') as matching,
               count(*) filter (where wrong_claim) as wrong_claims, count(*) as graded
        from grades group by system order by system""",
}


def records(path: Path) -> list[dict[str, Any]]:
    return [json.loads(line) for line in path.read_text().splitlines()]


def public_address() -> str:
    """This machine's public IPv4 address, the only one the writer endpoint will accept."""
    return httpx.get("https://api.ipify.org", timeout=30).raise_for_status().text.strip()


SECRET_KEYS = ("password", "secret", "connection", "uri", "dsn", "token")


def redacted(value: Any) -> Any:
    """A reply as it may be printed: every key that could carry the password dropped, at any depth."""
    if isinstance(value, dict):
        return {k: redacted(v) for k, v in value.items() if not any(s in k.lower() for s in SECRET_KEYS)}
    if isinstance(value, list):
        return [redacted(v) for v in value]
    return value


def rebuild_cluster(meko: Meko, ids: dict[str, str]) -> tuple[dict[str, Any], str]:
    """A new `dejafix` cluster with a writer endpoint: the cluster and its one-time password."""
    for cluster in meko.call("amp_cluster_list", **ids):
        if cluster["name"] == CLUSTER:
            meko.call("amp_cluster_delete", **ids, cluster_id=cluster["id"])
            print(f"deleted the old {CLUSTER} cluster", flush=True)
    created = meko.call(
        "amp_cluster_create",
        **ids,
        name=CLUSTER,
        with_writer=True,
        connectivity_mode="ingress_external",
        allowed_cidrs=[f"{public_address()}/32"],
    )
    password = created.pop("cloud_admin_password")
    print("created:", json.dumps(redacted(created))[:1500], flush=True)
    return created, password


def wait_for_endpoint(meko: Meko, ids: dict[str, str], created: dict[str, Any]) -> dict[str, Any]:
    """The writer endpoint on the cluster's default branch, once it is up and has an address."""
    cluster_id, branch_id = created["id"], created["default_branch"]["branch_id"]
    where = {"cluster_id": cluster_id, "branch_id": branch_id}
    deadline = time.monotonic() + READY_TIMEOUT
    seen = None
    while time.monotonic() < deadline:
        for listed in meko.call("amp_compute_list", **ids, **where):
            compute_id = listed.get("compute_id") or listed["id"]
            compute = meko.call("amp_compute_get", **ids, **where, compute_id=compute_id)
            shown = redacted(compute)
            if shown != seen:
                print("compute:", json.dumps(shown)[:1500], flush=True)
                seen = shown
            # Meko Cloud's endpoint record has no state field (checked 2026-11-23): an address is the sign;
            # connect() then retries until the endpoint takes connections.
            state = str(compute.get("state") or compute.get("status") or "ready").lower()
            if state in ("ready", "running", "active", "available") and compute.get("address"):
                return compute
        time.sleep(20)
    raise TimeoutError(f"the {CLUSTER} writer endpoint was not ready in {READY_TIMEOUT} s")


def public_dns(host: str) -> str | None:
    """`host`'s IPv4 address from a public resolver, or None while it has no record yet.

    A new endpoint's name gets its DNS record a few minutes after the address is reported; a lookup before
    then leaves a negative answer in the system resolver's cache (macOS kept it past 10 minutes, seen
    2026-11-23), so the address is asked of a public resolver and the name is kept for TLS."""
    done = subprocess.run(
        ["dig", "+short", "A", host, f"@{PUBLIC_RESOLVER}"], check=False, capture_output=True, text=True
    )
    addresses = [line for line in done.stdout.split() if re.fullmatch(r"\d+\.\d+\.\d+\.\d+", line)]
    return addresses[0] if done.returncode == 0 and addresses else None


def connect(compute: dict[str, Any], password: str) -> psycopg.Connection:
    """The writer endpoint's database, as its login user; a new endpoint refuses connections for a while."""
    host, _, port = compute["address"].partition(":")
    deadline = time.monotonic() + READY_TIMEOUT
    while True:
        address = public_dns(host)
        if address is None:
            if time.monotonic() > deadline:
                raise TimeoutError(f"{host} has no DNS record after {READY_TIMEOUT} s")
            print(f"no DNS record for {host} yet", flush=True)
            time.sleep(20)
            continue
        try:
            return psycopg.connect(
                host=host,
                hostaddr=address,
                port=int(port or 5432),
                user=compute.get("login_user") or "cloud_admin",
                password=password,
                dbname="postgres",
                sslmode="require",
                connect_timeout=30,
            )
        except psycopg.OperationalError as exc:
            if time.monotonic() > deadline or "password authentication failed" in str(exc):
                raise
            print(f"endpoint not taking connections yet: {str(exc).splitlines()[0][:200]}", flush=True)
            time.sleep(20)


def load(conn: psycopg.Connection, replays: dict[str, Path], judge: Path) -> None:
    pool, links = load_pool(), load_links()
    stream = load_stream()
    with conn.cursor() as cur:
        cur.execute(SCHEMA)
        for position, ticket in enumerate(stream, 1):
            issue = pool[ticket["number"]]
            cur.execute(
                "insert into tickets values (%s, %s, %s, %s, %s, %s)",
                (
                    issue["number"],
                    issue["title"],
                    issue["url"],
                    issue["createdAt"][:10],
                    ticket["role"],
                    position,
                ),
            )
        in_stream = {t["number"] for t in stream}
        cur.executemany(
            "insert into duplicate_links values (%s, %s)",
            [(dup, canon) for dup, canon in links.items() if dup in in_stream],
        )
        for system, path in replays.items():
            for rec in records(path):
                triage = rec.get("triage") or rec.get("baseline") or {}
                cur.execute(
                    "insert into outcomes values (%s, %s, %s, %s, %s, %s, %s)",
                    (
                        system,
                        rec["ticket"],
                        triage.get("verdict"),
                        triage.get("known_issue"),
                        rec["correct"],
                        rec.get("exact"),
                        rec.get("reply"),
                    ),
                )
                for run in rec["runs"]:
                    cur.execute(
                        "insert into agent_runs values (%s, %s, %s, %s, %s, %s, %s)",
                        (
                            system,
                            rec["ticket"],
                            run["role"],
                            run["tokens"],
                            run["cost_usd"],
                            run["seconds"],
                            [c["tool"] for c in run["calls"]],
                        ),
                    )
                if rec.get("learning_id"):
                    cur.execute(
                        "insert into learnings values (%s, %s, %s, %s, %s)",
                        (
                            rec["learning_id"],
                            system,
                            rec["ticket"],
                            rec.get("learning_filed_under", rec["ticket"]),
                            rec["learning"],
                        ),
                    )
        for rec in records(judge):
            for system, g in rec["grades"].items():
                cur.execute(
                    "insert into grades values (%s, %s, %s, %s, %s)",
                    (
                        rec["ticket"],
                        system.replace("baseline", "stuffed"),
                        g["resolution"],
                        g["wrong_claim"],
                        g["why"],
                    ),
                )
    conn.commit()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--datapack", default="dejafix-uv-final")
    parser.add_argument("--replay", action="append", required=True, help="system=path.jsonl")
    parser.add_argument("--judge", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=Path("results/amp-queries.json"))
    args = parser.parse_args()
    replays = {name: Path(path) for name, path in (item.split("=", 1) for item in args.replay)}
    datapack = loaded_datapack(args.datapack)
    if datapack.get("where") != "cloud":
        raise SystemExit(f"{args.datapack} is not a Meko Cloud datapack: AMP is Meko Cloud only")
    with Meko() as meko:
        ids = {"datapack_id": datapack["datapack_id"]}
        ids["conversation_id"] = conversation(meko, "dejafix-amp", "AMP tables", datapack["datapack_id"])
        created, password = rebuild_cluster(meko, ids)
        compute = wait_for_endpoint(meko, ids, created)
    print("endpoint:", redacted(compute), flush=True)
    with connect(compute, password) as conn:
        load(conn, replays, args.judge)
        answers = {}
        with conn.cursor() as cur:
            for name, sql in QUERIES.items():
                cur.execute(sql)
                columns = [d.name for d in cur.description]
                answers[name] = {
                    "sql": " ".join(sql.split()),
                    "rows": [
                        dict(
                            zip(
                                columns,
                                (
                                    str(v) if not isinstance(v, (int, bool, list, type(None))) else v
                                    for v in row
                                ),
                                strict=True,
                            )
                        )
                        for row in cur.fetchall()
                    ],
                }
    args.out.write_text(json.dumps(answers, indent=1))
    for name, answer in answers.items():
        print(name, answer["rows"])
    print(f"-> {args.out}")


if __name__ == "__main__":
    main()
